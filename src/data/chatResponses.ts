export const CHAT_MAP = new Map(CHAT_RESPONSES.map(r => [r.id, r]));

// Search function for dynamic responses
export function findChatResponse(userQuery: string): ChatResponse | undefined {
  const query = userQuery.toLowerCase();
  return CHAT_RESPONSES.find(response =>
    response.questions.some(q => q.toLowerCase().includes(query)) ||
    response.topic.toLowerCase().includes(query)
  );
}
